def _cell(s) -> str:
    return str(s if s not in (None, "") else "—").replace("|", "/").replace("\n", " ")


def generate_markdown(meeting_id: str) -> str:
    m = db.get_meeting(meeting_id)
    summ = db.get_summary(meeting_id) or {}
    tasks = db.list_tasks(meeting_id)
    decs = db.list_decisions(meeting_id)
    events = db.list_events(meeting_id)
    segs = db.get_segments(meeting_id)
    dur = m.get("duration_sec")
    L = [f"# Minutes of Meeting", "", f"**Meeting:** {m['title']}  ", f"**Date:** {pretty(m.get('date'))}  "]
    if dur:
        L.append(f"**Duration:** about {max(1, int(round(dur / 60)))} minutes  ")
    L.append(f"**Source:** {m.get('source_type') or 'transcript'}  ")
    L.append("**Prepared by:** MeetingAI (draft for review)  ")
    L += ["", "## Attendees"]
    att = m.get("attendees") or []
    L += [f"- {a}" for a in att] if att else ["- Not specified in the recording"]
    L += ["", "## Agenda"]
    ag = summ.get("agenda") or []
    if not ag:
        ag = summ.get("topics") or []
    L += [f"{i}. {a}" for i, a in enumerate(ag, 1)] if ag else ["1. Not specified"]
    L += ["", "## Summary", summ.get("overview") or "No summary is available for this meeting."]
    L += ["", "## Discussion Highlights"]
    L += [f"- {k}" for k in (summ.get("key_points") or [])] or ["- No highlights recorded."]
    L += ["", "## Decisions"]
    if decs:
        L += ["| # | Decision | Raised by | Time |", "|---|---|---|---|"]
        for i, d in enumerate(decs, 1):
            flag = " ⚠" if d.get("review_required") else ""
            L.append(f"| {i} | {_cell(d['text'])}{flag} | {_cell(d.get('speaker'))} | {fmt_ts(d.get('ts'))} |")
    else:
        L.append("No decisions were recorded.")
    L += ["", "## Action Items"]
    if tasks:
        L += ["| # | Task | Owner | Deadline | Priority | Status |", "|---|---|---|---|---|---|"]
        for i, t in enumerate(tasks, 1):
            dl = pretty(t["deadline"]) if t["deadline"] else (f"Not specified ({t['deadline_text']})" if t.get("deadline_text") else "Not specified")
            flag = " ⚠" if t.get("review_required") else ""
            L.append(f"| {i} | {_cell(t['title'])}{flag} | {_cell(t['owner'])} | {_cell(dl)} | {t['priority']} | {t['status']} |")
    else:
        L.append("No action items were recorded.")
    if events:
        L += ["", "## Scheduled Events", "| Event | Date | Time |", "|---|---|---|"]
        for e in events:
            L.append(f"| {_cell(e['title'])} | {pretty(e['date'])} | {_cell(e.get('time'))} |")
    concl = summ.get("conclusions") or []
    L += ["", "## Conclusions and Next Steps"]
    L += [f"- {c}" for c in concl] or ["- No conclusions recorded."]
    L += ["", "---", "_Draft generated by MeetingAI from the meeting transcript. Items marked ⚠ were uncertain and need confirmation. "
          "Please review and edit before sharing._"]
    return "\n".join(L)


# ---------------------------------------------------------------- markdown helpers
_ITALIC_STAR = r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])"
_ITALIC_UNDER = r"(?<!\w)_(.+?)_(?!\w)"


def _inline(s: str, code_fmt: str, bold: str, italic: str) -> str:
    """Shared inline formatter: `code`, **bold**, *italic*, _italic_ (output markup passed in)."""
    codes: list[str] = []

    def stash(m):
        codes.append(m.group(1))
        return f"\x00{len(codes) - 1}\x00"

    s = re.sub(r"`([^`]+)`", stash, s)
    s = _html.escape(s)
    s = re.sub(r"\*\*(.+?)\*\*", bold, s)
    s = re.sub(_ITALIC_STAR, italic, s)
    s = re.sub(_ITALIC_UNDER, italic, s)
    return re.sub(r"\x00(\d+)\x00", lambda m: code_fmt.format(_html.escape(codes[int(m.group(1))])), s)


def _inline_html(s: str) -> str:
    return _inline(s, '<code style="background:#eceefb;padding:1px 5px;border-radius:4px;font-size:.92em">{}</code>',
                   r"<strong>\1</strong>", r"<em>\1</em>")


def md_blocks(md: str):
    """Yield ('h1'|'h2'|'h3'|'p'|'ul'|'ol'|'table'|'hr', payload)."""
    lines = md.replace("\r", "").split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
        elif ln.strip().startswith("```"):
            i += 1
            code = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i]); i += 1
            i += 1
            yield "code", "\n".join(code)
        elif ln.startswith("### "):
            yield "h3", ln[4:]; i += 1
        elif ln.startswith("## "):
            yield "h2", ln[3:]; i += 1
        elif ln.startswith("# "):
            yield "h1", ln[2:]; i += 1
        elif re.match(r"^\s*---+\s*$", ln):
            yield "hr", None; i += 1
        elif ln.lstrip().startswith("|"):
            rows = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{2,}:?", c) for c in cells):
                    rows.append(cells)
                i += 1
            yield "table", rows
        elif re.match(r"^\s*[-*]\s+", ln):
            items = []
            while i < len(lines) and re.match(r"^\s*[-*]\s+", lines[i]):
                items.append(re.sub(r"^\s*[-*]\s+", "", lines[i])); i += 1
            yield "ul", items
        elif re.match(r"^\s*\d+[.)]\s+", ln):
            items = []
            while i < len(lines) and re.match(r"^\s*\d+[.)]\s+", lines[i]):
                items.append(re.sub(r"^\s*\d+[.)]\s+", "", lines[i])); i += 1
            yield "ol", items
        else:
            para = ln
            i += 1
            while i < len(lines) and lines[i].strip() and not re.match(r"^(#|\||\s*[-*]\s|\s*\d+[.)]\s|---)", lines[i]):
                sep = "\n" if para.endswith("  ") else " "      # two trailing spaces = hard line break
                para = para.rstrip() + sep + lines[i].lstrip()
                i += 1
            yield "p", para.strip()


def to_html(md: str) -> str:
    css = ("font-family:Segoe UI,Arial,sans-serif;color:#1b2140;line-height:1.55;max-width:760px;margin:auto;")
    out = [f'<div style="{css}">']
    for kind, p in md_blocks(md):
        if kind == "h1":
            out.append(f'<h1 style="color:#4a2fc4;border-bottom:3px solid #7c5cff;padding-bottom:8px;font-size:30px;margin:0 0 14px">{_inline_html(p)}</h1>')
        elif kind == "h2":
            out.append(f'<h2 style="color:#2c3a8c;margin:24px 0 8px;font-size:20px">{_inline_html(p)}</h2>')
        elif kind == "h3":
            out.append(f"<h3>{_inline_html(p)}</h3>")
        elif kind == "code":
            out.append(f'<pre style="background:#f1f2fb;padding:10px;border-radius:8px;font-size:12px;overflow:auto">{_html.escape(p)}</pre>')
        elif kind == "hr":
            out.append('<hr style="border:none;border-top:1px solid #d9dcf0;margin:20px 0">')
        elif kind == "p":
            out.append(f'<p style="margin:6px 0;font-size:15px">{_inline_html(p).replace(chr(10), "<br>")}</p>')
        elif kind in ("ul", "ol"):
            tag = kind
            out.append(f'<{tag} style="font-size:15px;margin:6px 0 6px 18px;padding:0">' + "".join(f"<li>{_inline_html(x)}</li>" for x in p) + f"</{tag}>")
        elif kind == "table":
            head, *rows = p
            t = ['<table style="border-collapse:collapse;width:100%;font-size:14px">',
                 "<tr>" + "".join(f'<th style="background:#4a2fc4;color:#fff;padding:8px;text-align:left">{_inline_html(c)}</th>' for c in head) + "</tr>"]
            for r in rows:
                t.append("<tr>" + "".join(f'<td style="border:1px solid #d9dcf0;padding:7px">{_inline_html(c)}</td>' for c in r) + "</tr>")
            t.append("</table>")
            out.append("".join(t))
    out.append("</div>")
    return "\n".join(out)


def to_plain(md: str) -> str:
    t = re.sub(r"\*\*(.+?)\*\*", r"\1", md)
    t = re.sub(r"(?<!\w)_(.+?)_(?!\w)", r"\1", t)
    return t


# ---------------------------------------------------------------- DOCX
def _add_runs(par, text: str):
    if "\n" in text:
        for k, line in enumerate(text.split("\n")):
            if k:
                par.add_run().add_break()
            _add_runs(par, line)
        return
    for part in re.split(r"(`[^`]+`|\*\*.+?\*\*|(?<![\w*])\*(?!\s).+?(?<!\s)\*(?![\w*])|(?<!\w)_.+?_(?!\w))", text):
        if not part:
            continue
        if part.startswith("`") and part.endswith("`") and len(part) > 2:
            r = par.add_run(part[1:-1]); r.font.name = "Consolas"
        elif part.startswith("**") and part.endswith("**") and len(part) > 4:
            r = par.add_run(part[2:-2]); r.bold = True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            r = par.add_run(part[1:-1]); r.italic = True
        elif part.startswith("_") and part.endswith("_") and len(part) > 2:
            r = par.add_run(part[1:-1]); r.italic = True
        else:
            par.add_run(part)


def to_docx(md: str) -> bytes:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(11)
    for kind, p in md_blocks(md):
        if kind == "h1":
            h = doc.add_heading(level=0)
            r = h.add_run(re.sub(r"\*\*", "", p)); r.font.color.rgb = RGBColor(0x4A, 0x2F, 0xC4)
        elif kind == "h2":
            h = doc.add_heading(level=1)
            r = h.add_run(p); r.font.color.rgb = RGBColor(0x2C, 0x3A, 0x8C)
        elif kind == "h3":
            doc.add_heading(p, level=2)
        elif kind == "hr":
            doc.add_paragraph("_" * 60)
        elif kind == "p":
            par = doc.add_paragraph()
            _add_runs(par, p)
        elif kind == "code":
            for line in p.split("\n"):
                par = doc.add_paragraph()
                par.paragraph_format.space_after = Pt(0)
                par.paragraph_format.left_indent = Pt(10)
                run = par.add_run(line if line else " ")
                run.font.name = "Consolas"
                run.font.size = Pt(8.5)
                run.font.color.rgb = RGBColor(0x2C, 0x3A, 0x8C)
            doc.add_paragraph()
        elif kind == "ul":
            for item in p:
                par = doc.add_paragraph(style="List Bullet")
                _add_runs(par, item)
        elif kind == "ol":
            for n, item in enumerate(p, 1):
                par = doc.add_paragraph()
                par.paragraph_format.left_indent = Pt(22)
                par.paragraph_format.first_line_indent = Pt(-16)
                par.paragraph_format.space_after = Pt(2)
                par.add_run(f"{n}.  ")
                _add_runs(par, item)
        elif kind == "table":
            head, *rows = p
            tb = doc.add_table(rows=1, cols=len(head))
            tb.style = "Light Grid Accent 1"
            for j, c in enumerate(head):
                cell = tb.rows[0].cells[j]
                cell.text = ""
                run = cell.paragraphs[0].add_run(re.sub(r"\*\*", "", c)); run.bold = True
            for r in rows:
                cells = tb.add_row().cells
                for j, c in enumerate(r[:len(head)]):
                    cells[j].text = ""
                    _add_runs(cells[j].paragraphs[0], c)
            doc.add_paragraph()
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


# ---------------------------------------------------------------- PDF
_PDF_MAP = {"⚠": "(!)", "—": "-", "–": "-", "→": "->", "←": "<-", "≥": ">=", "≤": "<=", "≈": "~", "…": "...", "·": "-",
            "“": '"', "”": '"', "‘": "'", "’": "'", "├─": "|-", "└─": "`-", "│": "|", "├": "|", "└": "`", "─": "-",
            "✅": "[ok]", "•": "-", "＋": "+"}


def _pdf_safe(s: str) -> str:
    """The built-in PDF fonts only cover Latin-1; map common symbols to plain ASCII."""
    for k, v in _PDF_MAP.items():
        s = s.replace(k, v)
    return s


def to_pdf(md: str) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import HRFlowable, ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontName="Helvetica", fontSize=10, leading=14, textColor=colors.HexColor("#1b2140"))
    cell = ParagraphStyle("c", parent=body, fontSize=8.5, leading=11)
    cellh = ParagraphStyle("ch", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontName="Helvetica-Bold", fontSize=22, textColor=colors.HexColor("#4a2fc4"), alignment=0)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold", fontSize=13, textColor=colors.HexColor("#2c3a8c"), spaceBefore=12)

    def esc(s):
        return _pdf_safe(_inline(s, '<font name="Courier" size="8.5">{}</font>', r"<b>\1</b>", r"<i>\1</i>"))

    def widths_for(head, rows, total):
        n = len(head)
        w = []
        for j in range(n):
            longest = max([len(re.sub(r"[*_`]", "", head[j]))] + [len(re.sub(r"[*_`]", "", r[j])) for r in rows if j < len(r)])
            w.append(min(max(longest, 3), 70) ** 0.8)
        tot = sum(w)
        w = [max(x / tot, 0.05) for x in w]
        tot = sum(w)
        return [total * x / tot for x in w]

    story = []
    for kind, p in md_blocks(md):
        if kind == "h1":
            story += [Paragraph(esc(p), h1), HRFlowable(width="100%", color=colors.HexColor("#7c5cff"), thickness=2), Spacer(1, 6)]
        elif kind in ("h2", "h3"):
            story.append(Paragraph(esc(p), h2))
        elif kind == "hr":
            story.append(HRFlowable(width="100%", color=colors.lightgrey))
        elif kind == "code":
            from reportlab.platypus import Preformatted

            story += [Preformatted(_pdf_safe(p), ParagraphStyle("code", fontName="Courier", fontSize=7.5, leading=9.5,
                                                                                         backColor=colors.HexColor("#f1f2fb"), leftIndent=6)), Spacer(1, 6)]
        elif kind == "p":
            story += [Paragraph(esc(p).replace("\n", "<br/>"), body), Spacer(1, 3)]
        elif kind in ("ul", "ol"):
            story.append(ListFlowable([ListItem(Paragraph(esc(x), body)) for x in p],
                                      bulletType="bullet" if kind == "ul" else "1", leftIndent=14))
        elif kind == "table":
            head, *rows = p
            data = [[Paragraph(esc(c), cellh) for c in head]] + [[Paragraph(esc(c), cell) for c in r[:len(head)]] + [""] * max(0, len(head) - len(r)) for r in rows]
            ncol = len(head)
            width = A4[0] - 40 * mm
            widths = widths_for(head, rows, width)
            t = Table(data, colWidths=widths, repeatRows=1)
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#4a2fc4")),
                                   ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c9cde8")),
                                   ("VALIGN", (0, 0), (-1, -1), "TOP"),
                                   ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f4f5fd")])]))
            story += [t, Spacer(1, 6)]
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
                      title="Minutes of Meeting").build(story)
    return buf.getvalue()
